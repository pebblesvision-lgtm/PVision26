"""Write web/engine/data.js from the Python source of truth, so the browser
engine and the Python app share finish names, hatch defaults, translations,
element templates and default outline parameters."""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pvsketch import hatch, i18n, project, templates  # noqa: E402


def main() -> None:
    tpl = {k: {"nl": v["nl"], "en": v["en"],
               "items": [list(i) for i in v["items"]]} for k, v in templates.ELEMENT_TEMPLATES.items()}
    data = {
        "STRINGS": i18n.STRINGS,
        "FINISH_NAMES": {k: list(v) for k, v in i18n.FINISH_NAMES.items()},
        "FINISH_DEFAULTS": hatch.FINISH_DEFAULTS,
        "ELEMENT_TEMPLATES": tpl,
        "DEFAULT_OUTLINE_PARAMS": project.DEFAULT_OUTLINE_PARAMS,
        "TITLEBLOCK_FIELDS": list(project.TITLEBLOCK_FIELDS),
        "VIEW_NAMES": __import__("pvsketch.views", fromlist=["x"]).VIEW_NAMES,
    }
    out = os.path.join(ROOT, "web", "engine", "data.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/gen_engine_data.py - do not edit */\n")
        f.write("(function (PV) {\n  Object.assign(PV, " + json.dumps(data, ensure_ascii=False, indent=1) + ");\n})(globalThis.PV = globalThis.PV || {});\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
